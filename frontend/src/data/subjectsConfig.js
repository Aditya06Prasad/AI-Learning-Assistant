export const getSubjectsForCourse = (courseName, boardName = null) => {
  if (!courseName) return [];
  
  if (boardName) {
    const key = `${boardName}_${courseName}`;
    return courseSubjects[key] || [];
  }

  // Regular course matching
  return courseSubjects[courseName] || [];
};
